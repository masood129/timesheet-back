-- =============================================
-- فایل 2: دسترسی به پروژه‌ها (ساده)
-- =============================================
-- این فایل دسترسی کارمندان به پروژه‌ها را تعریف می‌کند
-- =============================================

USE UMD;
GO

PRINT N'→ تعریف دسترسی به پروژه‌ها...';

-- حذف دسترسی‌های قبلی
DELETE FROM UserProjectAccess WHERE UserId IN (2001, 2002, 2003, 2004, 2005);

-- تعریف دسترسی‌ها
INSERT INTO UserProjectAccess (UserId, ProjectId)
VALUES
    -- کارمند 2001: دسترسی به 2 پروژه
    (2001, 100),
    (2001, 101),
    
    -- کارمند 2002: دسترسی به 3 پروژه
    (2002, 100),
    (2002, 102),
    (2002, 103),
    
    -- کارمند 2003: دسترسی به 1 پروژه
    (2003, 101),
    
    -- کارمند 2004: دسترسی به 2 پروژه
    (2004, 104),
    (2004, 105),
    
    -- کارمند 2005: دسترسی به 1 پروژه
    (2005, 106);

PRINT N'✓ دسترسی‌های پروژه ایجاد شد';
PRINT N'  2001 → پروژه 100, 101';
PRINT N'  2002 → پروژه 100, 102, 103';
PRINT N'  2003 → پروژه 101';
PRINT N'  2004 → پروژه 104, 105';
PRINT N'  2005 → پروژه 106';
GO
